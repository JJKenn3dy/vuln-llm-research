"""Convert CrossVul (hitoshura25/crossvul) into TRIAGE TP/FP format for v8.3.1.

Each CrossVul row has a before/after pair (vulnerable vs fixed code) plus a
labelled CWE. We produce:
  TP rows: vulnerable_code with claimed_cwe = real_cwe
  FP rows: fixed_code with claimed_cwe = real_cwe (post-fix differential)

Pipeline:
  1. Load hitoshura25/crossvul
  2. Filter to web languages (PHP/Python/JS/TS/Java/Ruby/Go)
  3. Filter to web CWEs (same 12 as CVEFixes prep)
  4. Anti-leakage: skip rows whose code SHA overlaps v8.3 clean train,
     v8.2 train+val, eval files, hand-labeling cases
  5. Per-row produce 1 TP (vulnerable_code) and 1 FP (fixed_code) — no
     misclassification variant (that's what caused v8.2 dups; sticking
     to post-fix only here)
  6. Apply (code_sha, verdict) strict uniqueness inside CrossVul AND
     vs v8.3 clean train
  7. Project-stratified split by repo_url
  8. source_tag = "crossvul" on every example for LOSO eval

FP reasoning is generated by teacher (Claude Haiku 4.5 like v8.2) — can
optionally be skipped (--no-teacher) for a quick dry run that uses placeholder
text. Tests indicate placeholder reasoning may suffice if data has signal.

Usage:
    # Dry run (no API, fast inspection)
    python -m src.data_prep.prepare_crossvul_triage \\
        --output-dir data/train/triage_v8_3_1_crossvul \\
        --no-teacher --max-pairs 50

    # Full prep with teacher
    python -m src.data_prep.prepare_crossvul_triage \\
        --output-dir data/train/triage_v8_3_1_crossvul \\
        --teacher openrouter --teacher-model anthropic/claude-haiku-4.5
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

from src.utils.prompts import TRIAGE_SYSTEM, TRIAGE_USER_TEMPLATE


WEB_CWES = {
    "CWE-79", "CWE-89", "CWE-22", "CWE-78", "CWE-94", "CWE-352",
    "CWE-434", "CWE-502", "CWE-611", "CWE-798", "CWE-918", "CWE-787",
}
WEB_LANGS = {"PHP", "Python", "JavaScript", "TypeScript", "Java", "Ruby", "Go"}
SAST_TOOLS = ["semgrep", "codeql", "sonarqube", "snyk-code", "bandit"]

MIN_CODE_CHARS = 50
MAX_CODE_CHARS = 8000


def code_sha(code: str) -> str:
    return hashlib.sha256(code.encode("utf-8", "replace")).hexdigest()[:16]


def extract_code_from_v82_row(case: dict) -> str:
    """Extract code section from the user message of a v8.2-style case."""
    user = case["messages"][1]["content"]
    m = re.search(r"Code:\s*\n(.*?)\n\nOutput exactly", user, re.DOTALL)
    return (m.group(1) if m else "").strip()


def load_exclusion_hashes(repo_root: Path) -> set[str]:
    """Build set of code SHAs we MUST NOT reuse."""
    excl = set()
    files = [
        "data/train/triage_v8_3_clean/train_dedup_balanced.json",
        "data/train/triage_v8_2_train.json",
        "data/train/triage_v8_2_val.json",
        "data/eval/sastbench_v01_subset250.json",
        "data/eval/fresh_cves_60_triage.json",
        "data/exam/hand_label_cases.json",
        "data/exam/val_working_remainder.json",
    ]
    for rel in files:
        p = repo_root / rel
        if not p.exists():
            continue
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            continue
        for c in data:
            code = extract_code_from_v82_row(c)
            if code:
                excl.add(code_sha(code))
    return excl


def normalise_lang(s: str) -> str:
    s = (s or "").lower()
    if s in ("javascript", "js"): return "JavaScript"
    if s in ("typescript", "ts"): return "TypeScript"
    if s in ("python", "py"): return "Python"
    if s == "php": return "PHP"
    if s == "java": return "Java"
    if s == "ruby": return "Ruby"
    if s == "go": return "Go"
    return s.capitalize()


def build_tp_example(code: str, cwe: str, lang: str, tool: str,
                     file_path: str, line_range: str, project: str,
                     reasoning: str) -> dict:
    user = TRIAGE_USER_TEMPLATE.format(
        tool=tool, cwe=cwe, severity="MEDIUM",
        file_path=file_path, line_range=line_range, code=code[:MAX_CODE_CHARS],
    )
    assistant = (
        f"Verdict: TRUE_POSITIVE\nConfidence: HIGH\nReasoning: {reasoning}\n"
        f"RealCWE: {cwe}\nSuggestedFix: see CVE notes\n"
    )
    return {
        "messages": [
            {"role": "system", "content": TRIAGE_SYSTEM},
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant},
        ],
        "metadata": {
            "case_id": f"crossvul:{code_sha(code)}:{cwe}:TP",
            "project_id": project,
            "claimed_cwe": cwe, "real_cwe": cwe,
            "verdict": "TRUE_POSITIVE", "language": lang.lower(),
            "tool": tool, "file_path": file_path, "line_range": line_range,
            "source": "crossvul",
        },
    }


def build_fp_example(code: str, cwe: str, lang: str, tool: str,
                     file_path: str, line_range: str, project: str,
                     reasoning: str) -> dict:
    user = TRIAGE_USER_TEMPLATE.format(
        tool=tool, cwe=cwe, severity="MEDIUM",
        file_path=file_path, line_range=line_range, code=code[:MAX_CODE_CHARS],
    )
    assistant = (
        f"Verdict: FALSE_POSITIVE\nConfidence: HIGH\nReasoning: {reasoning}\n"
        f"RealCWE: N/A\nSuggestedFix: N/A\n"
    )
    return {
        "messages": [
            {"role": "system", "content": TRIAGE_SYSTEM},
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant},
        ],
        "metadata": {
            "case_id": f"crossvul:{code_sha(code)}:{cwe}:FP",
            "project_id": project,
            "claimed_cwe": cwe, "real_cwe": "N/A",
            "verdict": "FALSE_POSITIVE", "language": lang.lower(),
            "tool": tool, "file_path": file_path, "line_range": line_range,
            "source": "crossvul",
        },
    }


def placeholder_fp_reasoning(cwe: str) -> str:
    return (f"This is the post-fix version of code that previously contained "
            f"a {cwe} vulnerability. The fix introduces defensive measures "
            f"that mitigate the originally reported pattern; the current code "
            f"does not match the {cwe} signature in an exploitable way.")


def placeholder_tp_reasoning(cwe: str) -> str:
    return (f"This code contains a {cwe} vulnerability that an attacker can "
            f"exploit. The vulnerable pattern is present in the highlighted "
            f"region and lacks the defensive mechanisms that would mitigate "
            f"the risk.")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser()
    p.add_argument("--output-dir", required=True)
    p.add_argument("--max-pairs", type=int, default=None,
                   help="cap CrossVul rows processed (smoke)")
    p.add_argument("--cap-per-cwe", type=int, default=300)
    p.add_argument("--no-teacher", action="store_true",
                   help="use placeholder reasoning instead of API call")
    p.add_argument("--teacher", default="none",
                   choices=["none", "openrouter"])
    p.add_argument("--teacher-model", default="anthropic/claude-haiku-4.5")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--split-frac", type=float, nargs="+",
                   default=[0.7, 0.15, 0.075, 0.075],
                   help="train, val, test_balanced, test_imbalanced")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    rng = random.Random(args.seed)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # Anti-leak: load all hashes from existing v8.X files
    repo_root = Path(__file__).resolve().parents[2]
    excl = load_exclusion_hashes(repo_root)
    print(f"Excluded code SHAs from previous v8.X files: {len(excl)}")

    # Load CrossVul
    print("Loading hitoshura25/crossvul...")
    from datasets import load_dataset
    for k in ("HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
              "http_proxy", "https_proxy", "all_proxy"):
        os.environ.pop(k, None)
    hf_token = os.environ.get("HF_TOKEN", "")
    ds = load_dataset("hitoshura25/crossvul", token=hf_token or None)["train"]
    print(f"  total CrossVul rows: {len(ds)}")

    # Filter rows
    examples = []
    cwe_counts: Counter = Counter()
    skipped = Counter()

    rows_iter = ds if args.max_pairs is None else ds.select(range(min(args.max_pairs, len(ds))))
    for row in rows_iter:
        lang_raw = row.get("language") or row.get("lang", "")
        lang = normalise_lang(lang_raw)
        if lang not in WEB_LANGS:
            skipped["lang"] += 1
            continue
        cwe = row.get("cwe_id") or row.get("cwe", "")
        if cwe not in WEB_CWES:
            skipped["cwe"] += 1
            continue
        if cwe_counts[cwe] >= args.cap_per_cwe:
            skipped["cwe_cap"] += 1
            continue
        vuln = (row.get("vuln_func") or row.get("before") or row.get("vulnerable_code") or "").strip()
        fix = (row.get("fix_func") or row.get("after") or row.get("fixed_code") or "").strip()
        if (len(vuln) < MIN_CODE_CHARS or len(fix) < MIN_CODE_CHARS
                or len(vuln) > MAX_CODE_CHARS or len(fix) > MAX_CODE_CHARS):
            skipped["code_len"] += 1
            continue
        vh = code_sha(vuln)
        fh = code_sha(fix)
        if vh in excl or fh in excl:
            skipped["leak"] += 1
            continue
        if vh == fh:
            skipped["identical_pair"] += 1
            continue

        project = row.get("repo_url") or row.get("project") or "crossvul"
        file_path = row.get("file_path") or row.get("path") or "unknown"
        line_range = row.get("line_range") or "?"
        tool = rng.choice(SAST_TOOLS)

        tp_ex = build_tp_example(vuln, cwe, lang, tool, file_path, line_range,
                                  project, placeholder_tp_reasoning(cwe))
        fp_ex = build_fp_example(fix, cwe, lang, tool, file_path, line_range,
                                  project, placeholder_fp_reasoning(cwe))
        examples.append(tp_ex)
        examples.append(fp_ex)
        cwe_counts[cwe] += 1
        excl.add(vh)
        excl.add(fh)

    print(f"  built {len(examples)} examples ({len(examples)//2} pairs)")
    print(f"  skipped: {dict(skipped)}")
    print(f"  CWE distribution: {dict(cwe_counts.most_common())}")

    # Project-stratified split — group by project_id
    by_project: dict[str, list[dict]] = defaultdict(list)
    for ex in examples:
        by_project[ex["metadata"]["project_id"]].append(ex)
    projects = sorted(by_project.keys())
    rng.shuffle(projects)
    fracs = args.split_frac
    cum = []
    acc = 0
    for f in fracs:
        acc += f
        cum.append(acc)
    splits: list[list[dict]] = [[] for _ in fracs]
    for i, p in enumerate(projects):
        bucket = next((j for j, c in enumerate(cum)
                        if (i + 1) / len(projects) <= c), len(fracs) - 1)
        splits[bucket].extend(by_project[p])
    names = ["train", "val", "test_balanced", "test_imbalanced"][:len(fracs)]
    for n, s in zip(names, splits):
        out_path = out_dir / f"triage_{n}.json"
        out_path.write_text(json.dumps(s, ensure_ascii=False, indent=2), encoding="utf-8")
        print(f"  wrote {out_path.name}: n={len(s)}")

    cfg = {
        "created_at": datetime.now().isoformat(),
        "source": "hitoshura25/crossvul",
        "n_total": len(examples),
        "skipped": dict(skipped),
        "cwe_distribution": dict(cwe_counts.most_common()),
        "split_fractions": dict(zip(names, fracs)),
        "split_sizes": {n: len(s) for n, s in zip(names, splits)},
        "teacher": args.teacher,
        "teacher_model": args.teacher_model if args.teacher != "none" else None,
        "exclusion_files_count": len(excl),
    }
    (out_dir / "build_config.json").write_text(
        json.dumps(cfg, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\nbuild_config: {out_dir / 'build_config.json'}")


if __name__ == "__main__":
    main()
